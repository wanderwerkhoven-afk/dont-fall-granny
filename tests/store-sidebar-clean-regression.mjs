import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('index.html','utf8');
const css=readFileSync('style.css','utf8');
const app=readFileSync('app.js','utf8');
new Function(app);
const styles=css.slice(css.lastIndexOf('/* v41 — Store pages have no sidebar navigation.'));
assert.ok(styles.length>1500,'the cleaner sidebar stylesheet must exist');
assert.match(styles,/\.menu-tabs button:not\(\.menu-back\)\{\s*display:none!important/,'hide all redundant sidebar tabs');
assert.match(styles,/\.menu-tabs \.menu-back\{/,'keep a visually subtle back action');
assert.match(styles,/grid-row:1 \/ 5!important/,'main store content spans full right column');
assert.match(styles,/\.store-brand\{[\s\S]*?grid-row:2!important/,'title below back action');
assert.match(styles,/\.menu-hero\{[\s\S]*?grid-row:3!important/,'preview retains its space');
assert.match(styles,/\.menu-meta\{[\s\S]*?grid-row:4!important/,'stats remain visible');
assert.match(styles,/@media\(max-width:650px\)/,'small screen adaptation');
assert.match(html,/class="menu-back"[^>]*data-page="home"|data-page="home" class="menu-back"/);
assert.ok(app.includes("menuTabs.addEventListener('click'"),'back routes through existing page navigation');
assert.match(css,/#overlay\.storepage #menuContent\{[\s\S]*?overflow:auto!important/,'store content remains scrollable');
console.log('PASS single back action, store layout, mobile ordering, existing routes and syntax');
