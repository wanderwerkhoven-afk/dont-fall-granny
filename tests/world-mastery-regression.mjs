import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const code=readFileSync('world-mastery.js','utf8');
const app=readFileSync('app.js','utf8');
const html=readFileSync('index.html','utf8');
const win={};new Function('window',code)(win);
const {WORLD_MASTERY,evaluate,progress,totalStars,normalizeStars}=win.GrannyWorldMastery;
assert.equal(WORLD_MASTERY.length,10);
assert.equal(new Set(WORLD_MASTERY.map(w=>w.id)).size,10);
assert.equal(WORLD_MASTERY.reduce((sum,w)=>sum+w.goals.length,0),30);
assert.equal(new Set(WORLD_MASTERY.flatMap(w=>w.goals.map(g=>g.sticker))).size,21);
const m={distance:0,perfects:0,nearMisses:0,bestCombo:0};
assert.deepEqual(normalizeStars(m),[false,false,false]);
assert.deepEqual(evaluate(0,m),[]);
assert.equal(progress(0,m).earned,0);
const xp=1170,coins=240,achievements=['first-run'];
const economy={xp,coins,achievements:[...achievements]};
m.distance=600;
let awards=evaluate(0,m);
assert.equal(awards.length,1);
assert.equal(awards[0].sticker,'Buurtbloem');
assert.deepEqual(normalizeStars(m),[true,false,false]);
assert.deepEqual(evaluate(0,m),[],'Star cannot be granted twice');
m.distance=0;
assert.deepEqual(evaluate(0,m),[],'Once earned, never revoke');
assert.deepEqual(normalizeStars(m),[true,false,false]);
m.perfects=2;m.nearMisses=4;
awards=evaluate(0,m);
assert.equal(awards.length,2);
assert.equal(progress(0,m).earned,3);
const saved=JSON.parse(JSON.stringify(m));
assert.equal(progress(0,saved).earned,3,'Saved stars survive JSON serialization');
const masteries={0:saved};
assert.equal(totalStars(masteries),3);
for(let i=1;i<WORLD_MASTERY.length;i++){
 const mm={distance:100000,perfects:1000,nearMisses:1000};
 assert.equal(evaluate(i,mm).length,3);
 masteries[i]=JSON.parse(JSON.stringify(mm));
}
assert.equal(totalStars(masteries),30);
assert.equal(evaluate(10,m).length,0);
assert.equal(xp,economy.xp);
assert.equal(coins,economy.coins);
assert.deepEqual(achievements,economy.achievements);
assert.match(app,/function addWorldMastery\(/);
assert.match(app,/WORLD_MASTERY\.evaluate\(currentTier%TIERS\.length,m\)/);
assert.match(app,/saveMetaState\(\); \/\/ Permanent at the exact milestone/);
assert.match(app,/function reconcileWorldMastery\(/);
assert.match(app,/function renderAdventureBook\(/);
assert.match(app,/OMA’S ADVENTURE BOOK/);
assert.match(app,/reconcileWorldMastery\(\);reset\(\);showMenu/);
assert.match(app,/grandma-meta-v1/);
assert.match(html,/world-mastery\.js\?v=21/);
new Function(app);
