import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const file='index.html';
const html=readFileSync(file,'utf8');
const old="background-image:url('./assets/hanger-spritesheet.png');";
const next="background-image:url('./assets/hanger-spritesheet.svg');";
assert.equal(html.split(old).length-1,1,'Expected exactly one old sprite reference');
const updated=html.replace(old,next);
writeFileSync(file,updated);
const svg=readFileSync('assets/hanger-spritesheet.svg','utf8');
assert.match(svg,/width="720" height="120"/);
assert.equal((svg.match(/<use href="#hanger"/g)||[]).length,6,'Need six complete frames');
assert.match(updated,/background-size:576px 96px/);
assert.match(updated,/background-size:504px 84px/);
assert.match(updated,/function setHangerFrame/);
assert.match(updated,/function syncClothesHanger/);
console.log('PASS: six vector frames, desktop/mobile geometry and scroll animation references');
